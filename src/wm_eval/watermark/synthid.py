"""SynthID Text configuration, via the official port in `transformers`.

Device-stability fix: transformers builds the SynthID sampling table with
`torch.Generator(device=...)`, and CPU and CUDA generators give *different* tables for the
same seed. Text watermarked on a GPU would then be undetectable on a CPU (and vice versa).
We therefore always build the table on CPU and move it to the generation device, both
during generation (via `StableSynthIDConfig`) and during detection.

The keys are derived at runtime from a secret env var (see WatermarkConfig.keys) and are
only ever passed to these objects, never to the recorder or to artifacts.
"""

from __future__ import annotations

import torch
from transformers import SynthIDTextWatermarkingConfig, SynthIDTextWatermarkLogitsProcessor

from wm_eval.config import WatermarkConfig


def _processor(
    ngram_len: int,
    keys: list[int],
    sampling_table_size: int,
    sampling_table_seed: int,
    context_history_size: int,
    device: str | torch.device = "cpu",
) -> SynthIDTextWatermarkLogitsProcessor:
    proc = SynthIDTextWatermarkLogitsProcessor(
        ngram_len=ngram_len,
        keys=keys,
        sampling_table_size=sampling_table_size,
        sampling_table_seed=sampling_table_seed,
        context_history_size=context_history_size,
        device=torch.device("cpu"),  # table generated by the CPU RNG, always
    )
    device = torch.device(device)
    proc.keys = proc.keys.to(device)
    proc.sampling_table = proc.sampling_table.to(device)
    proc.device = device
    return proc


class StableSynthIDConfig(SynthIDTextWatermarkingConfig):
    """Same as transformers' config, but the processor's sampling table is device-independent.
    Keeps transformers' placement of the watermark after all logits warpers."""

    def construct_processor(self, vocab_size: int, device) -> SynthIDTextWatermarkLogitsProcessor:
        return _processor(
            self.ngram_len,
            self.keys,
            self.sampling_table_size,
            self.sampling_table_seed,
            self.context_history_size,
            device,
        )


def generation_config(cfg: WatermarkConfig) -> StableSynthIDConfig:
    """Passed to `model.generate(watermarking_config=...)`; applied after temperature/top-k/top-p
    and immediately before sampling."""
    return StableSynthIDConfig(
        ngram_len=cfg.ngram_len,
        keys=cfg.keys(),
        sampling_table_size=cfg.sampling_table_size,
        sampling_table_seed=cfg.sampling_table_seed,
        context_history_size=cfg.context_history_size,
    )


def logits_processor(
    cfg: WatermarkConfig, device: str = "cpu"
) -> SynthIDTextWatermarkLogitsProcessor:
    """Same object generation uses; detection reuses its g-value and mask functions."""
    return _processor(
        cfg.ngram_len,
        cfg.keys(),
        cfg.sampling_table_size,
        cfg.sampling_table_seed,
        cfg.context_history_size,
        device,
    )


def public_fields(cfg: WatermarkConfig) -> dict:
    """Watermark parameters that are safe to record (no keys, no secret)."""
    return cfg.model_dump(exclude={"secret_env"})
